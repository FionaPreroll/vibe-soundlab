// Writes sources/index.json: the songs of the GitHub repositories listed in
// src/sources.js, with titles and credits read from their comments, pinned to each
// repository's latest commit. Needs git and network access: pnpm run sources
// It only reads the files as text; nothing from the repositories runs here.
import { execFileSync } from 'node:child_process';
import { lstatSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SOURCES, readSongInfo, songGroup } from '../src/sources.js';

export const INDEX_FILE = fileURLToPath(new URL('../sources/index.json', import.meta.url));
const MAX_BYTES = 256 * 1024;

/**
 * The index entry for one source from a checkout ({ commit, date, files: { path: code } }),
 * and the .js files it left out because they are not in one of the source's folders.
 * Songs come in the order of the folders, then by title.
 */
export function indexSource(source, { commit, date, files }) {
  const groups = Object.values(source.folders);
  const songs = [];
  const skipped = [];
  for (const [path, code] of Object.entries(files)) {
    const group = songGroup(source, path);
    if (group === null) skipped.push(path);
    else songs.push({ path, group, ...readSongInfo(code, path) });
  }
  songs.sort((a, b) => groups.indexOf(a.group) - groups.indexOf(b.group) || a.title.localeCompare(b.title, 'en', { sensitivity: 'base' }) || a.path.localeCompare(b.path));
  const { folders, ...about } = source;
  return { entry: { ...about, commit, date: date.slice(0, 10), songs }, skipped: skipped.sort() };
}

export const serialize = (sources) =>
  `${JSON.stringify({ _about: 'Songs from other GitHub repositories, pinned to one commit each. Generated by scripts/index-sources.js from src/sources.js; do not edit.', sources }, null, 1)}\n`;

const git = (dir, ...args) => execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8' }).trim();

/** Clones the repository's default branch and reads its .js files (no links, nothing huge). */
function checkout(repo) {
  const dir = mkdtempSync(join(tmpdir(), 'vibe-source-'));
  try {
    execFileSync('git', ['clone', '--quiet', '--depth', '1', '--no-recurse-submodules', `https://github.com/${repo}.git`, dir], { stdio: 'inherit' });
    const files = {};
    for (const path of git(dir, 'ls-files', '-z').split('\0')) {
      if (!/\.js$/i.test(path)) continue;
      const stat = lstatSync(join(dir, path));
      if (stat.isFile() && stat.size <= MAX_BYTES) files[path] = readFileSync(join(dir, path), 'utf8');
    }
    return { commit: git(dir, 'rev-parse', 'HEAD'), date: git(dir, 'log', '-1', '--format=%cI'), files };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const entries = [];
  for (const source of SOURCES) {
    const { entry, skipped } = indexSource(source, checkout(source.repo));
    entries.push(entry);
    console.log(`${source.repo} @ ${entry.commit.slice(0, 7)} (${entry.date}): ${entry.songs.length} songs`);
    if (skipped.length) console.log(`  left out (not in a song folder): ${skipped.join(', ')}`);
  }
  mkdirSync(dirname(INDEX_FILE), { recursive: true });
  writeFileSync(INDEX_FILE, serialize(entries));
  console.log('sources/index.json updated');
}
